DEFAULT_LANGUAGE = "en"


def _pretty_key(value: str) -> str:
    """Readable fallback for a new block or field missing from a help table."""
    text = str(value or "").replace("_", " ").strip()
    return " ".join(text.split()).title() or "Block"


def _table(language: str):
    """(help, shared) for a language, falling back to Russian.

    English lives in its own module so the two stay readable side by side
    rather than as a dict of dicts of dicts.
    """
    if str(language).lower().startswith("ru"):
        return HELP, SHARED
    try:
        from . import block_help_en as en
        return en.HELP, en.SHARED
    except Exception:
        return HELP, SHARED


def apply_to(block_types, language: str = DEFAULT_LANGUAGE) -> None:
    """Merge labels and help into the catalog in place, in one language.

    Overwrites rather than setdefault: the catalog is re-decorated whenever
    the language changes, and a setdefault would leave the first language
    baked in forever.
    """
    help_table, shared = _table(language)
    for spec in block_types:
        entry = help_table.get(spec["type"], {})
        spec["label"] = entry.get("label") or _pretty_key(spec["type"])
        spec["desc"] = entry.get("desc") or _pretty_key(spec["type"])
        field_entries = entry.get("fields", {})
        for field in spec["fields"]:
            key = field["key"]
            info = field_entries.get(key) or shared.get(key) or {}
            # An untranslated field still has to render, so it falls back to
            # its key rather than to a row labelled with nothing at all.
            field["label"] = info.get("label") or _pretty_key(key)
            field["help"] = info.get("help") or _pretty_key(key)


def missing(language: str):
    """Which strings a translation is still missing -- so a half-finished
    language shows up as a test failure rather than as blank tooltips and
    fields labelled with their key."""
    help_table, shared = _table(language)
    gaps = []
    for block_type, entry in HELP.items():
        target = help_table.get(block_type)
        if not target or not target.get("desc"):
            gaps.append(block_type)
            continue
        if not target.get("label"):
            gaps.append("%s.label" % block_type)
        for key in entry.get("fields", {}):
            info = target.get("fields", {}).get(key) or {}
            if not info.get("help"):
                gaps.append("%s.%s" % (block_type, key))
            if not info.get("label"):
                gaps.append("%s.%s.label" % (block_type, key))
    for key in SHARED:
        info = shared.get(key) or {}
        if not info.get("help"):
            gaps.append("SHARED.%s" % key)
        if not info.get("label"):
            gaps.append("SHARED.%s.label" % key)
    return gaps
